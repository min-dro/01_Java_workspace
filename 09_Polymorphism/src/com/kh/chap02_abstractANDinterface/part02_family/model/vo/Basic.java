package com.kh.chap02_abstractANDinterface.part02_family.model.vo;

// 인터페이스
public interface Basic {

	/*
	 * * 인터페이스
	 * > 모든 필드가 "상수필드" 이고, 모든 메소드가 "추상메소드" 인 일종의 "추상클래스"
	 * 
	 * [ 표현법 ]
	 * 
	 *  패키지선언부; // 나의 위치를 알려줌
	 *  
	 *  접근제한자 interface 인터페이스명 {
	 *  
	 *  	// 필드부 - 상수필드로만 이루어져야함 (static final)
	 *  
	 *  	// 생성자부 - 쓰기 않음 (어파피 객체 생성이 불가할거니까)
	 *  	// > 없는게 정의 상 맞음!!
	 *  
	 *  	// 메소드부 - 추상메소드로만 이루어져야 함 (abstract)
	 *  	
	 *  }
	 *  
	 *  - 인터페이스는 결국 클래스다!!
	 *  - 인터페이스에서 모든 필드는 무조건 상수필드
	 *  - 안티페이스에서 모든 메소드는 무조건 추상메소드
	 *  - 무조건 구현해야하는게 있을 때 인터페이스를 만들어서 코드 (추상메소드) 를 물려주게 된다.
	 *  
	 *  - 추상클래스와 다르게 좀 더 강한 규칙성, 강제성을 띄는 게 인터페이스임!!
	 *  예)
	 *  일반메소드4개 + 추상메소드1 개짜리 추상클래스를 상속받았다고 한다면 자식클래스에서 오버라이딩을 적어도 1개만 해주면 됨!!
	 *  추상메소드5 개짜리 인터페이스를 상속받았다고 한다면 자식클래스에서 오버라이딩을 5개 모두 다 해줘야 함!! (강제성이 더 쎔)
	 *  
	 *  * extends 와 implements
	 *  - 클래스 간의 상속 관계일 때 (단일상속)
	 *    자식클래스명 extends 부모클래스명
	 *    : 부모클래스로부터 코드를 물려받아 온 뒤, "내가 원하는 코드를 더 덧붙여서" 확장해서 쓰겠다.
	 *  - 클래스와 인터페이스 사이의 구현 관계일 때
	 *    자식클래스명 implements 인터페이스명, 인터페스명, ...
	 *    : 인터페이스로부터 껍데기 뿐인 코드를 물려받아 온 뒤, "내가 원하는 코드로 채워넣어서" 구현해서 쓰겠다.
	 *  - 인터페이스 간의 상속 관계일때 (다중상속)
	 *    자식인터페이스명 extends 부모인터페이스명, 부모인터페이스명, ...    
	 *   
	 *    
	 *  * 인터페이스는 다중 상속이 허용된다!!
	 *  > 모든 메소드가 추상메소드이기 때문에 결국 최종 구현은
	 *    자식클래스에서 단 한번만 해줘도 충분
	 *  > 모든 필드가 상수필드이기 때문에 클래스명.상수필드명 으로 접근해서
	 *    필드명이 중복되더라도 전혀 상관 없기 때문
	 *    
	 *  * 추상클래스와 인터페이스
	 *  1. 공통점
	 *  - 객체 생성 안되나, 참조변수로써 사용될 수 있다. (즉, 다형성을 적용할 수 있다)
	 *  - 상속받는 (구현받는) 클래스에 추상메소드를 오버라이딩 하도록 강제할 수 있다
	 *  
	 *  2. 차이점
	 *  - 추상클래스는 클래스 내에 인스턴스 변수, 일반메소드를 작성 가능하고,
	 *    추상메소드가 포함되었거나 또는 추상메소드가 포함되지 않더라도 abstract 키워드로 클래스가 정의됨
	 *  - 강제성이 추상클래스보다 인터페이스가 더 쎄다. 통일성 또한 줄 수 있다.
	 *  - 존재하는 목적이 다르다. *** (개념)
	 *    추상클래스는 상속받아서 코드를 가져다 쓰고 + 내가 필요한 코드를 덧붙여서 코드를 확장 (extends) 하는 목적
	 *    인터페이스 껍데기 뿐인 코드를 받아와서 그 내용을 단순히 채워넣어서 구현해서 (implements) 쓸 목적
	 *    (메소드의 구현, 즉, 동작을 강제하기 위해 주로 쓴다 - 구현 객체의 같은 동작을 보장할 수 있다)
	 */
	
	// 필드부 - 상수필드만
	/* public static final */ int NUM = 10;
	// > 인터페이스의 필드부에는 애초에 "상수필드" 만 정의할 수 있기 때문에
	//	 public static final 이 생략 가능하다!! (암묵적, 묵시적 표현법)
	
	// 메소드부 - 추상메소드만
	/* public abstract */ void eat();
	
	public abstract void sleep();
	// > 인터페이스의 메소드부에는 애초에 "추상메소드" 만 정의할 수 있기 때문에
	//	 public abstract 가 생략 가능하다!! (암묵적, 묵시적 표현법) 쓸 목적
	
	
}
