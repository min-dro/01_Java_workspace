/*
 * * 자바 프로그래밍 순서
 * 1. workspace 생성 : 하나의 "작업 공간" 단위를 나타내는 폴더
 * 2. project 생성 : 하나의 "프로그램" 단위를 나타내는 폴더
 * 3. package 생성 : 프로젝트의 src 폴더 내부에 존재하는 "소스코드들을 보관하는 폴더"
 * 4. class 생성 : "자바 소스 코드의 최소 단위" 로 .java 파일 한개 단위에 해당함
 * 				  패키지 안에 비슷한 역할의 소스코드 (클래스) 끼리 보관한다.
 * 
 * * 패키지
 * > 프로젝트 내 src 폴더 안에 존재하는 소스코드들을 보관하는 폴더
 * 
 * * 패키지 생성 시 주의사항
 * 1. 한 패키지 내에 동일한 이름의 클래스를 생성 불가 (중복 불가)
 * - 단, 서로 다른 패키지 안에 동일한 이름의 클래스들은 생성 가능!!
 * 2. 한 패키지 내에 동일한 이름의 패키지들 생성 불가 (중복 불가)
 * - 단, 서로 다른 패키지 안에 동일한 이름의 패키지들은 생성 가능!!
 * 3. 기본패키지에 클래스를 만드는 것은 권장하지 않음
 * - src 폴더에 그냥 클래스를 만드는 것은 권장하지 않음 (가능은 하지만 권장하진 않음)
 * 	 모든 클래스들을 그냥 기본패키지에 몰아넣으면 수많은 소스코드들을 관리하기 힘들어짐
 * 	 코드들을 패키지별로 카테고리로 분류하여 관리해야 추후 유지보수에도 용이함
 * 	 기본패키지 (src 폴더) 에 만들어진 코드들은 다른 패키지에서 가져다 쓰지 못함 (가장 큰 이유)
 * 
 * * 패키지 생성 시 권장사항
 * 1. 패키지명은 모두 소문자로
 * - 풀클래스명을 봤을 때 어디까지가 패키지명이고 어디가 클래스명인지 한눈에 보이기 때문
 * 2. 패키지는 적어도 세 단계 이상으로 만들어주는 걸 권장
 * 예) com.kh.first, com.kh.second 등..
 * 3. 패키지명의 두 번째 레벨까지는 "도메인 주소", 의 역순으로 짓는다.
 * - 도메인 주소 : 웹 사이트에 접속하기 위한 고유한 주소
 * - 패키지만 봐도 어느 회사인지 제작한 소스코드인지를 한번에 파악 가능!!
 * 예) www.naver.com, www.google.com, ...
 */

