package com.kh.first;
// > 패키지 선언부
//	 이 클래스를 생성할 때 선택한 패키지의 위치를 나타내주는 구문, 삭제하면 안됨
//	 단, 기본패키지에 클래스를 만들면 패키지 선언부가 없음!!

/*
 * * 클래스 (Class)
 * > 자바 소스코드의 최소 단위
 * 	 자바에서 모든 코드는 이 클래스 안에 반드시 존재해야 하며,
 * 	 한 개의 클래스 = 한 개의 .java 파일이 됨
 */

// > 클래스 선언부
//	 클래스의 이름을 확인 가능 (HelloWorld)
//	 클래스의 풀클래스 명 : com.kh.first.HelloWorld
public class HelloWorld { // HelloWorld 클래스 영역 시작
	
	// 이 클래스 선언부 내부 {} 영역 안쪽에 실질적인 코드를 작성함!!
	
	/*
	 * * 메소드 (Method)
	 * > 사전적으로 "기능" 을 의미함 (하나의 기능 단위)
	 * > 한 개의 클래스 안에 여러 개의 메소드를 작성할 수 있음!!
	 * > 원칙적으로 한 개의 클래스 안에 메소드명이 중복되면 안되지만,
	 * 	 어떠한 규칙에 의해 메소드의 이름은 중복이 가능하긴 함.. => 추후 객체 시간에 다룰 것!!
	 * > 클래스 안에 메소드를 작성하고 그 안에 소스코드를 작성할것임!!
	 * 	 (클래스 안에 곧바로 소스코드 작성 불가)
	 * 이렇게 작성한 메소드 안의 코드를 실행하려면 "호출" 이라는 과정을 거쳐야함!!
	 * 
	 * * 메소드의 종류
	 * 1. main 메소드
	 * - 프로그램의 시작점 (Entry Point) 을 나타내는 부분
	 * - 프로그램이 실행되는 순간 제일 먼저 실행되는 메소드
	 * - 한 프로그램 당 적어도 1개 이상은 꼭 갖고 있어야함!!
	 * 2. 일반 메소드
	 * - main 메소드를 제외한 나머지 메소드들을 모두 메소드라고 지정함
	 * - 다른 메소드에서 "호출" 을 통해서만 실행시킬 수 있음
	 */
	
	// main 메소드 만들기
	public static void main(String[] args) { // main 메소드 영역 시작
		
		// 이 안에 소스코드 작성

		// * 출력문
		// > 이클립스의 콘솔창으로 텍스트 형식을 내보내주는 구문
		
		System.out.println("Hi Everyone!");
		// ; 은 마침표 역할!! 모든 구문 뒤에 반드시 써줘야함!! (중괄호 제외)
		
		System.out.println("Hello World^^");
		// > System.out.println 구문은 해당 값을 출력 후 줄바굼 O (Enter 키를 친 효과)
		//	 println 의 ln은 line 의 약자임!!
		
		System.out.print("안녕하세요");
		// > System.out.print 구문은 해당 값을 출력 후 줄바꿈 X
		
		System.out.print("여러분 ~!");
		// > 값 출력 후 줄바꿈을 하고싶다면? (반가워요^0^ 를 아래에 출력하고 싶다면?)
		
		// 방법1) 위의 출력문을 println 으로 바꾸기
		// 방법2) print 구문으로 출력하되, \n (개행문자) 추가하기
		// 방법3) System.out.println(); 을 그냥 실행시키기
		System.out.println();
		// > 출력할 내용은 없지만 줄바꿈은 하겠다.
		
		System.out.print("반가워요^0^\n");
		
		System.out.println("\'안\t녕\t히\t계\t세\t요\'");
		//  > \n (개행문자) 를 꼭 출력할 구문 뒤에만 쓰라는 법은 없음!!
		
		/*
		 * * Escape 문자
		 * > 특수 역할을 하는 문자들로, \ (역슬래시) 와 한개의 문자를 결합해서 사용한다.
		 * 
		 * \n : 개행 (Enter 키)
		 * \t : 수평탭, 들여쓰기 (tap 키)
		 * \\ : \ (역슬래시 라는 문자 자체를 의미)
		 * \' : 홑따옴표
		 * \" : 쌍따옴표
		 */
		
		/*
		 * * 알게모르게 출력문 내용이 위에서부터 아래로 한줄 한줄씩 순서에 맞게 실행되는 것을 볼 수 있음!!
		 * > 모든 프로그래밍 언어로 짜여진 코드들은 항상 "위에서부터 아래로 한줄 한줄씩 흐른다."
		 *   (프로그램의 기본 흐름)
		 */
	} // main 메소드 영역 끝

} // HelloWorld 클래스 영역 끝

/*
 * * 자바의 명명 규칙
 * > Project 명, Package 명, class 명,  Method 명 등 이름을 짓는 것은 내 마음대로지만,
 * 	 왠만해서는 명명 규칙을 지켜주는 것이 좋다.
 * 
 * 1. 영어 사용
 * 2. 띄어쓰기 불가
 * 3. 의미 부여를 해서 여러 단어를 조합해서 짓는다.
 * 예) 01_MyFirstProject
 * 4. 패키지명은 소문자로 적는다.
 * 5. 클래스명의 첫글자는 무조건 대문자로 적는다.
 * 6. 메소드명의 첫글자는 무조건 소문자로 적는다.
 * 7. 변수명의 첫글자는 무조건 소문자로 적는다. => 내일 마저 확인
 * 8. 공통 원칙 : 여러 개의 단어를 조합해서 이름을 짓는 것은 좋은데,
 * 				띄어쓰기가 불가하므로 각 단어별로 첫글자는 "대문자" 로 표현해서 가독성을 높여준다.
 * 예) 클래스명 : methodTest (X) --> MethodTest (O)
 * 	  메소드명 : TestPrint (X) --> testPrint	(O)
 * 
 * > 낙타 표기법 (낙타봉 표기법, 낙타등 표기법, ...), Camel Case 라고 부름!!
 */

