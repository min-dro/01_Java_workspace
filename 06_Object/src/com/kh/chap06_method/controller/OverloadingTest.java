package com.kh.chap06_method.controller;

// 메소드 "오버로딩 (Overloading)" 개념
public class OverloadingTest { // 클래스 영역 시작

	/*
	 * * 메소드 오버로딩
	 * 
	 * > 한 클래스 내에 "같은 메소드명" 으로 여러개의 메소드를 정의할 수 있는 규칙
	 * > 한 클래스 내에 "같은 메소드명" 으로 여러개의 메소드를 원칙상 정의 불가!!
	 * 	 이 "오버로딩" 규칙을 적용하면 (개념을 적용하면) 그게 가능해짐!!
	 * 
	 * * 메소드 오버로딩의 성립조건
	 * 1. 메소드명은 동일해야한다.
	 * 2. 매개변수의 자료형, 갯수, 순서가 하나라도 다르게 작성되어야만 한다. (즉, 매개변수가 일치하면 안된다)
	 * 3. 단, 매개변수명, 접근제한자의 종류, 반환형은 메소드 오버로딩에 영향을 주지 않는다.
	 * 
	 * 예)
	 * 생성자를 여러개 두는 것 - 오버로딩의 아주 대표적인 예시
	 * (반환형이 없고 클래스명과 이름이 같은 일종의 "메소드")
	 */
	
	public void test() { // 메소드 영역 시작
		
		// 메소드 오버로딩이 너무 잘 되어있는 예시
		// 1. 생성자
		// 2. 출력문 *** (출력메소드)
		
		// 출력메소드 종류
		// System.out.println(출력할내용);
		// System.out.print(출력할내용);
		// System.out.printf("출력형식", 출력할값);
		// > 사실 System 이라는 클래스 어딘가에 정의된 메소드형태!! (출력할내용이 사실은 인자값이었음)
		
		System.out.println("안녕하세요"); // 매개변수 1개 (String)
		System.out.println(100); // 매개변수 1개 (int)
		System.out.println(true); // 매개변수 1개 (boolean)
		System.out.println('a'); // 매개변수 1개 (char)
		// > 메소드명은 동일하나 매개변수의 자료형이 "다른" 상황
		
		System.out.printf("%d", 10); // 매개변수 2개 (String, int)
		System.out.printf("%f %d", 0.1, 22); // 매개변수 3개 (String, double, int)
		System.out.printf("%s %f", "안녕하세요", 0.01); // 매개변수 3개 (String, String, double)
		// > 메소드명은 동일하나 매개변수의 자료형, 갯수, 순서가 "다른" 상황
		
	} // 메소드 영역 끝
	
	/*
	public void test() { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	*/
	// > Duplicate method test() 오류 발생
	//	 원칙 상으로는 한 클래스 내에 동일한 이름의 메소드 여러개 작성 불가!!
	
	public void test(int a) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	// > 오버로딩이 성립되었다.
	//	 (메소드명이 같으나, 위의 test 메소드와 비교했을 때 매개변수의 갯수가 다름)
	
	public void test(int a, String s) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	// > 오버로딩이 성립되었다.
	//	 (위의 test 메소드들과 비교했을 때 매개변수의 갯수가 다름)
	
	public void test(String s, int i) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	// > 오버로딩이 성립되었다.
	//	 (위의  test 메소드와 비교했을 때 매개변수의 갯수는 같으나 순서가 다름)
	
	public void test(int a, int b) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	// > 오버로딩이 성립되었다.
	//	 (위의 test 메소드들과 비교했을 때 매개변수의 갯수는 같으나 자료형이 다름)
	
	/*
	public void test(int c, int d) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	*/
	// > 오버로딩이 성립되지 않았다.
	// (위의 test 메소드와 비교했을 때 매개변수의 종류, 갯수, 순서가 모두 같음)
	// 매개변수의 종류, 갯수, 순서가 같되, 매개변수의 이름만 다른 상황임!!
	
	public void test(int a, int b, String s) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	// > 오버로딩이 성립되었다.
	//	 (위의 test 메소드들과 비교했을 때 매개변수의 갯수가 다름_
	
	/*
	public int test(int a, int b, String s) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	*/
	// > 오버로딩이 성립되지 않았다.
	//	 (반환형이 다르더라도, 매개변수의 종류, 갯수, 순서가 모두 같음)
	
	/*
	private void test(int a, int b String s) { // 메소드 영역 시작
		
	} // 메소드 영역 끝
	*/
	// > 오버로딩이 성립되지 않았다.
	//	 (접근제한자가 다르더라도, 매개변수의 종류, 갯수, 순서가 모두 같음)
	
} // 클래스 영역 끝
