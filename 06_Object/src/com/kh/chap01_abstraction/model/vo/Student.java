package com.kh.chap01_abstraction.model.vo;

/*
 * * 자바 클래스의 구조
 * 
 * public class 클래스명 {
 * 
 * 		// 필드부
 * 		// > "필드" 들이 모여있는 "부"분
 * 
 * 		// 생성자부
 *		// > "생성자" 들이 모여있는 "부"분
 * 
 *		// 메소드부 
 *		// > "메소드" 들이 모여있는 "부"분
 *
 * }
 * 
 * - 클래스는 위와 같이 필드부, 생성자부, 메소드부 이렇게 3등분 해서 코드를 작성할 수 있다!!
 * - 이 필드부, 생성자부, 메소드부가 모두 존재하지 않아도 된다!! (내 필요에 따라 각 부분을 조합해서 씀)
 * 	 그래서 그동안 우리가 만들었던 클래스는 "메소드부" 만 존재하던 클래스로 만들어서 쓴거임!!
 */

// 현실세계의 학생들을 추상화 해서 만들 클래스 (이름, 나이, 키)
public class Student { // 클래스 영역 시작

	// [ 필드부 ]
	// "필드" 들이 모여있는 "부"분
	// 필드 == 전역변수 == 맴버변수 == 인스턴스변수
	
	// 필드 : 클래스 영역 안에, 메소드 영역 밖에 존재하는 변수
	//	      정의된 클래스 영역 안에서는 다 이 변수 (필드) 를 가져다 쓸 수 있게 됨 (어느 메소드든지 간에)
	//	      그래서 "전역변수 (global varibable)" 라고도 부름!!
	
	// 접근제한자 자료형 변수명;
	
	// > 접근제한자 : 이 필드에 접근할 수 있는 범위를 제한을 걸 수 있음!!
	//	 public > proctected > default > private
	//	 클래스 영역 안에서 필드를 선언할 때 반드시 접근제한자를 앞에 써야 함!! (안써도 문제가 되진 않음)
	
	public String name; // 이름을 담을 필드 (변수)
	public int age; // 나이를 담을 필드 (변수)
	public double height; // 키를 담을 필드 (변수)
	
	
	// [ 생성자부 ]
	
	// [ 메소드부 ]
	
} // 클래스 영역 끝









