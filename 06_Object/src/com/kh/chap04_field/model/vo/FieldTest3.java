package com.kh.chap04_field.model.vo;

// 클래스 변수 (static 변수) 와 상수 필드 (static final) 에 대해
public class FieldTest3 { // 클래스 영역 시작
	
	// 필드부
	
	/*
	 * * 필드 선언
	 * 
	 * [ 표현법 ]
	 * 접근제한자 (예약어) 자료형 필드명;
	 * > 예약어는 생략 가능
	 * 
	 * * 클래스 변수 (static 변수) 선언 방법
	 * 접근제한자 static 자료형 필드명;
	 * > 예약어 자리에 static 이 들어가는 경우를 클래스 변수 또는 static 변수라고 부름
	 */
	
	public static String sta = "static 변수";
	// > static 예약어가 붙는 순간, 클래스 변수 (static 변수) 로 취급됨
	// - 생성시점 : 프로그램 시작과 동시에 메모리의 Static 영역에 할당됨 (생성됨)
	// - 소멸시점 : 프로그램 종료되는 시점에 같이 소멸됨
	
	/*
	 * * static
	 * - 프로그램 시작과 동시에 메모리영역에 미리 다 올려두고
	 * 	 두고두고 언제 어디서나 가져다 쓸 수 있다.
	 * 
	 * - static 은 "공유", "재사용" 의 의미가 강함
	 * 	 (주로 공통코드 작업 시 많이 쓰임)
	 * 
	 * - static 은 많이 쓰지 않는 것이 좋음
	 * - 메모리 공간 효율을 위해 보통은 일반메소드 일반맴버변수로 많아 쓴다!!
	 */
	
	/*
	 * * 상수 필드
	 * 
	 * - 값을 변경할 수 없는 필드 (setter 메소드가 무의미해짐)
	 * 
	 * [ 표현법 ]
	 * public static final 자료형 변수명 = 값;
	 * 
	 * - 한번 지정된 값을 고정해서 공유해가면서 쓰겠다.
	 * - 무조건 초기화 구문까지 같이 작성해야함!!
	 * - 단, 예약어의 순서는 상관이 없음 (final static 이라고 써도 됨)
	 * 
	 * static : 공유, 재사용의 의미
	 * final : 고정된 값의 의미 (상수)
	 * 
	 * - 값이 변경되서는 안되는 고정적인 값을 메모리 상에 단 한번만 올려주고
	 * 	 공유해가면서 계속 사용할 목적
	 * - 상수명은 항상 "대문자" 로
	 */
	
	// 상수 필드
	public static final int NUM = 10;
	// > 상수의 의미이기 때문에 setter 를 만들지 않음
	//	 public 이기 때문에 getter 를 만들지 않음
	
	// 생성자부
	
	// 메소드부
	public static void test() { // 메소드 영역 시작
		
		System.out.println("안녕?");
	} // 메소드 영역 끝

} // 클래스 영역 끝
