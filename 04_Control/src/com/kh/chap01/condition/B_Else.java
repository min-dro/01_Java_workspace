package com.kh.chap01.condition;

import java.util.Scanner;

// if-else문, if-else if문
public class B_Else { // 클래스 영역 시작

	/*
	 * * if-else문
	 * > 조건식 한 개를 제시해서 한번에 두 개의 경우의 수를 나타낼 수 있는 선택문
	 * 
	 * 참고) 단독 if문은 조건식 한 개를 제시해서 한번에 한 개의 경우의 수만 나타낼 수 있었음!!
	 * 
	 * [ 표현법 ]
	 * if(조건식) {
	 * 
	 * 		조건식의 결과가 true 일 경우 실행할 구문;
	 * 
	 * } else {
	 * 
	 * 		조건식의 결과가 false 일 경우 실행할 구문;
	 * }
	 * 
	 * - 조건식의 결과가 true 일 경우
	 * if 블록({여기}) 안의 코드가 실행된 후 if-else문 자체를 빠져나감
	 * - 조건식의 결과가 false 일 경우
	 * else 블록 ({여기}) 안의 코드가 빠져나감
	 */
	
	// 단독 if문--> if-else문
	
	public void method1() { // 메소드 영역 시작
		
		// 사용자에세 정수를 입력받은 후 짝수인지 홀수인지 판별
		
		Scanner sc = new Scanner(System.in);
		
		System.out.print("정수를 입력하세요 : ");
		int num = sc.nextInt();
		sc.nextLine();
		
		// if-else문 버전
		/*
		if((num % 2) == 0) {
			// 첫번째 경우의 수 : 짝수일 경우
			
			System.out.println("짝수입니다.");
			
		} else {
			// 두번째 경우의 수 : 짝수가 아닐 경우 (즉, 홀수일 경우)
			
			System.out.println("홀수입니다.");
		}
		*/
		
		// > 단독 if문을 두번 쓰는것과 차이점이라고 한다면
		//	 단독 if문 때에는 조건식이 2번 나왔음!! (짝수인 조건식, 홀수인 조건식) - 조선 검사를 2번 해야함
		//	 if-else문에서는 조건식이 1번만 나옴!! (짝수인 조건식) - 조선 검사를 1번만 해도 됨!!
		// > 그럼에도 불구하고 결과는 같게 나오게 됨!! (컴퓨터 입장에서는 if-else문을 쓰는 것이 더 효율적)
		
		// 양수이면서 짝수인경우, 양수이면서 홀수인경우를 나타내고 싶음!!
		// > 우선 양수인지만 먼저 체크
		if(num > 0) {
			// 양수일 경우
			
			// num 이 양수일 경우에만 이 안에서 짝수인지 홀수인지 판별하기!!
			
			if((num % 2) == 0) {
				// 첫번째 경우의 수 : 짝수일 경우
				
				System.out.println("양수이면서 짝수입니다.");
				
			} else {
				// 양수가 아닐 경우
				
				System.out.println("양수가 아닙니다.");
				
				// > 만약 양수가 아닐 경우에는 추가적으로 음수인지, 0인지 판별을 또 하고 싶다면?
				//	 else 블록 안에서도 또 중첩해서 판별 가능함!!
			}
			
		}
		
		/*
		 * * if-else if문
		 * > 한번에 세 개 이상의 경우의 수를 나타내고 싶을 때 쓰는 선택문
		 * 
		 * [ 표현법 ]
		 * if(조건식1) {
		 * 
		 * 			조건식1 이 true 일 경우 실행할 코드;
		 * 
		 * } else if(조선식2) {
		 * 
		 * 			조건식2 가 true 일 경우 실행할 코드;
		 * 
		 * } else if(조건식3) {
		 * 
		 * 			조건식3 이 true 일 경우 실행할 코드;
		 * 
		 * } else {
		 * 
		 * 			 앞에 제시한 조건식1 ~ 조건식3 까지 검사 결과가 모두 false 일 경우 실행할 코드;
		 * }
		 */
	}
	
	public void method2() { // 메소드 영역 시작
			
		// 사용자로부터 정수를 입력 받아 양수인지, 0인지, 음수인지 판별 후 출력
			
		Scanner sc = new Scanner(System.in);
			
		System.out.print("정수를 입력하세요 : ");
		int num = sc.nextInt();
		sc.nextLine();
		
		//if-else if문 버전
		if(num > 0) {
			// 첫번째 경우의 수 : 양수일 경우
			
			System.out.println("양수입니다.");
			
		} else if(num == 0) {
			// 두번째 경우의 수 : 0일 경우
			
			System.out.println("0입니다");
			
		} else {
			// 세번째 경우의 수 : 양수도 아니고, 0도 아닐 경우 (즉, 음수일 경우)
			
			System.out.println("음수입니다.");
		}
		
	} // 메소드 영역 끝
	
	public void method3() { // 메소드 영역 시작
		
		// 나이를 입력받은 후 어린이인지, 청소년인지, 성인인지 판별 후 결과 출력
		// > 어린이는 13세 이하, 청소년은 13세 초과 ~ 19세 이하, 성인은 19세 초과
		//	 (판별 하되, 나이가 음수로 입려될 경우에는 "나이를 잘못 입력했습니다." 를 출력)
		
		Scanner sc = new Scanner(System.in);
		int age = sc.nextInt();
		sc.nextLine();
		
		System.out.print("나이를 입력하세요 : ");
		if(age < 0) {
			// 나이가 음수로 입력된 경우
			
			System.out.println("나이를 잘못 입력했습니다.");
			
		} else {
			// 나이가 음수로 입력되지 않은 경우 (즉, 제대로 입력한 경우)
			
			// 나이가 제대로 입력되었으니 이제야 판별 시작
			if(age <= 13) {
				// 첫번째 경우의 수 : 어린이일 경우
				
				System.out.println("어린이입니다.");
				
			} else if(/* (13< age) && */ (age<=19)) {
				// 두번째 경우의 수 : 청소년일 경우
				
				// (13 < age) && 조건을 지워도 제대로 동작할것임!!
				// > 위의 if 블록을 건너뛰고 이 else if 블록까지 도달했다라는 것은
				// 	 이미 위의 if 블록에서 언급된 age 가 13 초과인 경우라는 뜻임!!
				// > 암묵적으로 이미 age 는 13 를 초과한 상태로 넘어온 것이기 때문에
				//	 굳이 조건식에서 (13 < age) && 조건식을 빼더라도 제대로 동작하는것!!
				
				System.out.println("청소년입니다.");
				
			} else {
				// 세번째 경우의 수 : 어린이도 아니고, 청소년도 아닐 경우 (즉, 성인일 경우)
				
				System.out.println("성인입니다.");
			}
		}
		
	} // 메소드 영역 끝
	
	public void method4() { // 메소드 영역 시작
		
		// 사용자에게 점수를 입력받은 후
		// 90점 이상인 경우 "A등급"
		// 80점 이상인 경우 "B등급"
		// 70점 이상인 겨웅 "C등급"
		// 70점 미만인 경우 "D등급"
		// > "당신의 점수는 xx점이고, X등급입니다." 출력
		//	 (단, 점수는 음수가 될 수 없고, 만점은 100점임)
		
		Scanner sc = new Scanner(System.in);
		
		System.out.print("점수를 입력하세요 : ");
		int score = sc.nextInt();
		sc.nextLine();
		
		// 점수는 0 ~ 100점 사이
		// 등급을 판별하기 전에 우선 제대로된 점수를 입력했는지부터 보기!!
		if((0 <= score) && (score <= 100)) {
			// 제대로된 점수를 입력한 경우
			
			// 등급을 나타내는 변수를 미리 셋팅해두기
			// > 등급을 나타내는 변수는 제대로된 점수를 입력한 경우에 두고두고 가져다 써야 되기 때문!!
			char grade = ' ';
			// > char 타입의 경우 일반적으로 공백문자 ('')로 초기화한다!!
			
			// 예시) 지역변수 (local variable) 초기화
			// String str = "";
			// > String 타입의 경우 일반적으로 빈 문자열 ("") 로 초기화한다!! - 내용물이 없는 문자열
			//	 참고로 char 에는 빈 문자('') 개념이 없음!! 오류 주의!!
			// byte, short, int, long 의 경우 보통은 0.0 으로 초기화
			// float, double 의 경우 보통은 0.0 으로 초기화
			// boolean 은 기본적으로 false 로 초기화
			
			// 1. 변수는 선언된 영역 {여기} 내에서만 쓸 수 있음 (영역 밖에서는 사용 불가) => "지역변수" 개념
			// 2. 변수는 선언된 영역 {여기} 안에서는 이름이 중복될 수 없음!!
			// 3. "지역변수" 의 경우 항상 "초기화" 후 사용하는것을 권장한다.
			// > 빈 상자로 두고 나중에 필요할 때 값을 채워서 쓰지 말고, 미리 뭐라도 좀 채워두고나서 나중에라도 쓰자
			
			// 제대로된 점수를 입력했다면 이제서야 등급 판별을 시작함!!
			if(score >= 90) {
				// 첫번째 경우 : 90점 이상인 경우 (A등급)
				
				// System.out.printf("당신의 점수는 %d점이고, 등급은 %c등급입니다.\n", score, 'A');
				
				// 등급을 나타내는 변수에 'A' 담기
				grade ='A';
				
			} else if((80 <= score) /* && (score < 90) */) {
				// 두번째 경우 : 80점 이상 90점 미만인 경우 (B등급)
				
				// System.out.printf("당신의 점수는 %d점이고, 등급은 %c등급입니다.\n", score, 'B');
				
				// 등급을 나타내는 변수에 'B' 담기
				grade = 'B';
				
			} else if((70 <= score )/* && (score < 90) */) {
				// 세번째 경우 : 70점 이상 80점 미만인 경우 (C등급)
				
				// System.out.printd("당신의 점수는 %d점이고, 등급은 %c등급입니다.\n", score, 'C');
				grade = 'C';
				
			} else {
				// 네번째 경우 : D등급인 경우
				
				// System.out.printf("당신의 점수는  %d점이고, 등급은 %c등급입니다.\n", score, 'D');
				
				// 등급을 나타내는 변수에 'D' 담기
				grade = 'D';
			}
			
			// > 위의 등급판별용 조건문에서 결과를 매번 출력하지 않고,
			//	 조건문에서는 등급을 판병하는 용도로만 쓰고, 등급이 다 판별된 이 시점에서 한번에 출력을 써보기!!
			System.out.printf("당신의 점수는 %d점이고, 등급은 %c등급입니다.\n", score, grade);
			
		} else {
			// 제대로된 점수를 입력하지 않은 경우
			
			System.out.println("점수를 잘못 입력했습니다.");
		}
		
	} // 메소드 영역 끝
	
	
	
} // 클래스 영역 끝
	