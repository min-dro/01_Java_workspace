	/*
	 * * while문
	 * > 반복 횟수가 다소 명확하지 않을 때 사용하는 반복문
	 * > 조건식을 제시하고, 그 조건검사 결과가 매번 true 냐 false 냐에 따라 반복을 더 진행할지 말지를 판별하는 원리
	 * 
	 * [ 표현법 ]
	 * - 원래 while 문 표현법
	 * while(조건식) { // 조건검사 결과가 매번 true
	 * 
	 * 		반복적으로 실행할 구문;
	 * }
	 * 
	 * - for문과 유사한 형태로 표현법 변경 (초기식 -> 조건식 -> 반복구문 -> 증감식)
	 * 초기식;
	 * while(조건식) {
	 * 
	 * 		반복적으로 실험할 구문;
	 * 		증감식;
	 * }
	 * 
	 * - 초기식과 증감식은 while문에서 필수가 아님!! (그래서 횟수가 명확하지 않을 때 주로 쓰임)
	 * - 매번 조건검사를 하고 조건검사 결과가 true 라면 해당 구문을 실행, false 가 되는 순간 빠져나옴
	 * - 만약 의도적으로 무한 반복을 돌리고 싶다면 while(true) 라고 쓴다. (for(;;)랑 같은뜻임)
	 */
	
	public void method1() { // 메소드 영역 시작
	
		// "안녕하세요" 를 5번 출력
		
		// for문 버전
		/*
		for(int i = 0; i < 5; i++) {
		
			System.out.println("안녕하세요");
			
			i++; // 증감식
		}
		*/
		
		// while문 버전
		int i = 0; // 초기식
		
		while(i < 5) { // 조건식
			
			System.out.println("안녕하세요");
			
			i++; // 증감식
		}
		
	} // 메소드 영역 끝
	
