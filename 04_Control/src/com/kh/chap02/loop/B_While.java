	/*
	 * *  do-while문
	 * > 별도의 조건 검사 없이 반복 시작 전 무조건 해당 구문을 한번 미리 시작하고 나서 반복이 진핸되는 구조
	 * 
	 * [ 표현법 ]
	 * 
	 * do {
	 * 
	 * 		반복적을 실행할 코드;
	 * 
	 * } while(조건식);
	 * 
	 * - 별도의 조건검사 없이 무조건 실행할 코드를 한번 먼저 실행
	 * 	 (즉, 조건 검사 결과가 처음부터 false 여도 한번은 실행된다)
	 * - 그 후 조건식을 이용해서 조건검사 진행 후 해당 조건검사 결과가 true 라면 실행할 코드를 다시 진행
	 * 															   false 라면 반복문을 빠져나옴 	
	 * 
	 */
	
	public void method7() { // 메소드 영역 시작
		
		// while문
		/*
		int num = 1;
		
		while(num == 0) {
			
			System.out.println("안녕");
			num++;
		}
		*/
		// > 조건식에 의해 조건섬사를 먼저 하고 true 라면 반복이 시작되는 구조
		//	 에초에 처음부터 조건이  false 인 경우 반복이 단 한번도 진행되지 않음!! (0번)
		
		// do-while문
		int num = 1;
		
		do {
			
			System.out.println("안녕");
			num++;
			
		} while(num == 0);
		// > 우선 실행할 구문을 한번 실행 후 그다음에 조건식에 의해 조건검사가 일어나는 구조
		//	 에초에 처음부터 조건이 false 인 경우 반복이 한번은 적어도 진행됨!! (1번)
		
		// > do-while문은 개발자가 원하는 반복 횟수 + 1회
		//	 do-while문을 가지고 내가 원하는 반복 횟수를 잘 지정하려면
		//	 +1회 될 것을 감안하면서 조건식의 조정이 필요함!!
		//	 (이런 특징 때문에 실제로 잘 쓰이지는 않음)
		
	} // 메소드 영역 끝
	
