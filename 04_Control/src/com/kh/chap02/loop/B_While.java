	public void method3() { // 메소드 영역 시작
		
		// "1 2 3 4 5" 출력
		// > 규칙 : 시작수는 1, 끌수는 5포함, 1씩 증가
		
		// for(int i = 1; i<= 5; i++)
		
		// while문 버전
		int i = 1;
		
		while(i <= 5) {
			
			System.out.println(i++ + " ");
			
			// i++;
			// > 증감식을 생략하는 대식 출력 구문 안쪽에서
			//	 i가 출력되고 나서 1 증가될 수 있게끔 "후위" 연산자를 이용할 수도 있음!!
		}
		
		System.out.println();
		System.out.println("i : " + i); // 6
		
		// 이제는 i 가 6인 상태!!
		 
		// "5 4 3 2 1" 출력
		// > 규칙 : 시작수 6 (지금 i 가 6이라서), 끌수는 1 포함, 1씩 감소
		
		// int i = 6; // 초기식
		
		while(i > 1) {
			
			// i--;
			System.out.println(--i + " ");
			// > 이번에는 전위연산자를 이용해서 증감식 작성해봄!!
		}
		
		System.out.println();
		System.out.println("최종 i : " + i); // i
		
	} // 메소드 영역 끝
	
